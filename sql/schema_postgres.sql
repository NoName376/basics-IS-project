CREATE TABLE IF NOT EXISTS families (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL,
    invite_code TEXT        NOT NULL UNIQUE,
    currency    TEXT        NOT NULL DEFAULT 'KZT',
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id     BIGINT      NOT NULL REFERENCES families (id) ON DELETE CASCADE,
    full_name     TEXT        NOT NULL,
    email         TEXT        NOT NULL UNIQUE,
    password_hash TEXT        NOT NULL,
    role          TEXT        NOT NULL DEFAULT 'member'
                              CHECK (role IN ('admin', 'member')),
    is_active     SMALLINT    NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id           BIGINT    NOT NULL REFERENCES families (id) ON DELETE CASCADE,
    name                TEXT      NOT NULL,
    kind                TEXT      NOT NULL CHECK (kind IN ('expense', 'income')),
    monthly_limit_cents BIGINT    CHECK (monthly_limit_cents IS NULL OR monthly_limit_cents > 0),
    is_active           SMALLINT  NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    CONSTRAINT uq_category_name UNIQUE (family_id, name, kind)
);

CREATE TABLE IF NOT EXISTS transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id    BIGINT      NOT NULL REFERENCES families (id) ON DELETE CASCADE,
    user_id      BIGINT      NOT NULL REFERENCES users (id),
    category_id  BIGINT      NOT NULL REFERENCES categories (id),
    kind         TEXT        NOT NULL CHECK (kind IN ('expense', 'income')),
    amount_cents BIGINT      NOT NULL CHECK (amount_cents > 0),
    occurred_on  DATE        NOT NULL,
    note         TEXT        NOT NULL DEFAULT '',
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_transactions_family_date
    ON transactions (family_id, occurred_on DESC);

CREATE INDEX IF NOT EXISTS ix_transactions_category
    ON transactions (category_id);

CREATE INDEX IF NOT EXISTS ix_users_family
    ON users (family_id);

-- Compatibility view kept from Alibek's dump: his queries
-- (SELECT * FROM user_balance) keep working on the merged schema.
-- The FILTER form and the family_id join come from his own definition.
CREATE OR REPLACE VIEW public.user_balance AS
SELECT
    u.id AS user_id,
    u.full_name,
    ROUND(COALESCE(SUM(t.amount_cents) FILTER (WHERE t.kind = 'income'), 0) / 100.0, 2) AS total_income,
    ROUND(COALESCE(SUM(t.amount_cents) FILTER (WHERE t.kind = 'expense'), 0) / 100.0, 2) AS total_expenses,
    ROUND(
        (COALESCE(SUM(t.amount_cents) FILTER (WHERE t.kind = 'income'), 0)
         - COALESCE(SUM(t.amount_cents) FILTER (WHERE t.kind = 'expense'), 0)) / 100.0,
        2
    ) AS balance
FROM public.users u
LEFT JOIN public.transactions t
    ON t.user_id = u.id
   AND t.family_id = u.family_id
GROUP BY u.id, u.full_name;
